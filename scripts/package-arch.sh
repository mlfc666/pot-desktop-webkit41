#!/usr/bin/env bash
# Build an Arch Linux package (`.pkg.tar.zst`) for pot.
#
#   scripts/package-arch.sh [--target <triple>]
#
# Tauri 1 has no Arch backend, so the package is assembled by hand: an Arch
# package is a zstd-compressed tar holding the payload plus a `.PKGINFO` file.
# pacman only cares about those two things, so this works from any Linux host
# (the CI builds it on Ubuntu) and installs with `pacman -U` on Arch, Manjaro,
# EndeavourOS, CachyOS, …
#
# Dependency names are Arch's (`webkit2gtk-4.1`, `gtk3`, `libsoup3`, …), not
# Debian's: they are listed explicitly because there is no ldd → package
# database on a non-Arch build host.
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."
root=$PWD

target=""
while [[ $# -gt 0 ]]; do
  case $1 in
    --target) target=$2; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

[[ $(uname -s) == Linux ]] || { echo 'Build this package on Linux.' >&2; exit 1; }
command -v zstd >/dev/null || { echo 'Install zstd.' >&2; exit 1; }

version=$(python3 -c "import json;print(json.load(open('src-tauri/tauri.conf.json'))['package']['version'])")
case $(uname -m) in
  x86_64)  pkgarch=x86_64 ;;
  aarch64|arm64) pkgarch=aarch64 ;;
  *) echo "unsupported machine: $(uname -m)" >&2; exit 1 ;;
esac
pkgrel=1

outdir=$root/target/arch
mkdir -p "$outdir"

if [[ -n ${BIN:-} ]]; then
  binary=$BIN
else
  candidates=()
  [[ -n $target ]] && candidates+=("src-tauri/target/$target/release/pot")
  candidates+=("src-tauri/target/release/pot")
  for c in "${candidates[@]}"; do
    [[ -x $c ]] && { binary=$c; break; }
  done
fi
[[ -n ${binary:-} && -x ${binary:-} ]] || { echo "missing pot binary; build first" >&2; exit 1; }

stage=$(mktemp -d); trap 'rm -rf "$stage"' EXIT
install -d "$stage/usr/bin" "$stage/usr/share/applications" \
          "$stage/usr/share/icons/hicolor/512x512/apps" "$stage/usr/share/doc/pot" "$stage/usr/share/metainfo"

install -m755 "$binary" "$stage/usr/bin/pot"
strip --strip-all "$stage/usr/bin/pot" 2>/dev/null || true
install -m644 src-tauri/icons/icon.png "$stage/usr/share/icons/hicolor/512x512/apps/pot.png"
install -m644 LICENSE "$stage/usr/share/doc/pot/copyright"
[[ -f com.pot_app.pot.metainfo.xml ]] && install -m644 com.pot_app.pot.metainfo.xml "$stage/usr/share/metainfo/"

cat > "$stage/usr/share/applications/pot.desktop" <<'DESK'
[Desktop Entry]
Type=Application
Name=Pot
Comment=A cross-platform text translation and OCR app
Comment[zh_CN]=跨平台划词翻译和 OCR 软件
Exec=pot
Icon=pot
Terminal=false
Categories=Utility;Translation;
Keywords=translate;ocr;dictionary;
StartupWMClass=pot
DESK

size=$(du -sb "$stage" | cut -f1)
cat > "$stage/.PKGINFO" <<EOF
# Generated by scripts/package-arch.sh
pkgname = pot
pkgbase = pot
pkgver = ${version}-${pkgrel}
pkgdesc = Cross-platform text translation and OCR app (WebKitGTK 4.1 build)
url = https://pot-app.com
builddate = $(date -u +%s)
packager = pot-app <pot-app@users.noreply.github.com>
size = ${size}
arch = ${pkgarch}
license = GPL-3.0-only
depend = webkit2gtk-4.1
depend = gtk3
depend = libsoup3
depend = libayatana-appindicator
depend = tesseract
depend = openssl
depend = fontconfig
depend = freetype2
depend = libxcb
depend = libxkbcommon
depend = zlib
depend = bzip2
depend = libpng
depend = brotli
optdepend = tesseract-data-eng: English OCR data
optdepend = tesseract-data-chi_sim: Simplified Chinese OCR data
optdepend = noto-fonts-cjk: CJK fonts
EOF

out="$outdir/pot-${version}-${pkgrel}-${pkgarch}.pkg.tar.zst"
tar --zstd -cf "$out" -C "$stage" .PKGINFO usr
(cd "$outdir" && sha256sum "$(basename "$out")" > "$(basename "$out").sha256")
echo "built $out ($(du -h "$out" | cut -f1))"
